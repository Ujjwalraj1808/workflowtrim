"""Developer study: prepare repair pull requests (nothing is sent by this script).

Candidates are the RQ3 manual-review repairs that both reviewers judged correct (rq3/review_resolved.csv).
For each one the script checks, on the live repository:
  - the repository is not archived, and a pull request was merged in the last 90 days (maintained);
  - the workflow file on the default branch is unchanged since the RQ3 snapshot, so the reviewed diff applies;
  - CONTRIBUTING / AI-policy files are flagged for a manual read (some projects refuse tool-generated PRs).
The repair is regenerated with the current tool on the current file. For S1 the timeout comes from the
workflow's own run history (savings.timeouts_from_runs: 1.5 x P95 of successful job durations, at least
20 successful jobs), not the fixed 30 minutes of the RQ3 review; without enough history the S1 candidate is
skipped. At most one pull request per repository and PER_SMELL per smell, chosen in a random order (seed 2028).

Outputs: pr/candidates.csv (every candidate, with the reason it was kept or skipped) and, for each kept one,
pr/<id>/<file> (the repaired workflow), pr/<id>/diff.patch and pr/<id>/body.md (the pull-request text).
pr/tracking.csv is created empty for recording what happens to each pull request.

Run:  GITHUB_TOKEN=... python pr_study.py
"""
import base64
import csv
import os
import random
from datetime import datetime, timedelta, timezone

import requests

from workflowtrim.repair import check, diff, repair
from workflowtrim.rules import detect
from workflowtrim.savings import API, _api, estimate_from_runs, fetch_jobs

OUT = "pr"
SEED = 2028
PER_SMELL = 6
ACTIVE_DAYS = 90
MAX_HISTORY_RUNS = 60
POLICY_FILES = ["CONTRIBUTING.md", ".github/CONTRIBUTING.md", "docs/CONTRIBUTING.md", "AI_POLICY.md",
                ".github/AI_POLICY.md"]
POLICY_WORDS = ["ai-generated", "ai generated", "llm", "chatgpt", "copilot", "generated by ai", "bot",
                "automated pull request", "automated pr"]

SMELL_TEXT = {
    "S1": ("add `timeout-minutes` to jobs that have none",
           "A job without `timeout-minutes` can run for up to 360 minutes (GitHub's default) when it hangs. "
           "The value {timeout} minutes is 1.5 times the 95th percentile of the successful job durations of this "
           "workflow in its recent run history ({samples} jobs), so normal runs are not affected."),
    "S2": ("cancel superseded pull-request runs",
           "When a new commit is pushed to a pull request, the run for the previous commit keeps running. The "
           "added `concurrency` block cancels it, but only for `pull_request` events: runs for pushes to "
           "branches and tags (for example deployments) each get their own group and are never cancelled."),
    "S3": ("enable the dependency cache of the setup action",
           "Dependencies are downloaded again on every run. The setup action already supports caching keyed on "
           "the lock file; this change only turns it on with the lock file that the install command uses."),
    "S5": ("do not run the scheduled job in forks",
           "When the owner of a fork enables Actions, scheduled workflows run in the fork as well, on the fork "
           "owner's minutes. The added `if` lets scheduled runs execute only in this repository; other "
           "events are unchanged."),
    "S6": ("avoid running the workflow twice for the same commit",
           "With both `push` and `pull_request` triggers, a commit pushed to a pull-request branch in this "
           "repository runs the workflow twice. Restricting `push` to the default branch keeps one run per "
           "commit; pull requests are still checked by the `pull_request` trigger."),
    "S8": ("set a retention period for uploaded artifacts",
           "Artifacts are kept for 90 days by default and count towards the repository's storage. "
           "`retention-days: 7` keeps them long enough to inspect a run; if the project needs them longer, "
           "please tell us and we will change the value."),
}

BODY = """This pull request makes one small change to `.github/workflows/{file}`: {title}.

**Why.** {why}

**What changes.** Only the lines in the diff; no job or step is added, removed or reordered. The change was
checked automatically (the file parses, `actionlint` reports no new error) and reviewed by hand.

**Context.** We are a student research team at Galgotias University (India) studying configurations in GitHub
Actions workflows that use compute minutes or storage without need ("resource-waste smells"). The change was
produced by our open-source tool WorkflowTrim (https://github.com/Ujjwalraj1808/workflowtrim) and reviewed by
a person before submission. We will report, without naming people, whether such changes are accepted.

If this is not useful for the project, please just close the pull request; we will not send further ones.
Thank you for your time!
"""


def gh(path):
    return _api(f"{API}/{path}")


def maybe(path):
    """The API answer, or None when the resource does not exist (404). Other errors (no token, rate limit,
    access denied) stop the script, so they are never mistaken for a missing repository."""
    try:
        return gh(path)
    except requests.HTTPError as e:
        if e.response is not None and e.response.status_code == 404:
            return None
        raise


def file_text(repo, path, ref):
    data = maybe(f"repos/{repo}/contents/{path}?ref={ref}")
    if not data or "content" not in data:
        return None
    return base64.b64decode(data["content"]).decode("utf-8", errors="replace")


def norm(text):
    return text.replace("\r\n", "\n").rstrip("\n")


def merged_recently(repo):
    since = datetime.now(timezone.utc) - timedelta(days=ACTIVE_DAYS)
    pulls = maybe(f"repos/{repo}/pulls?state=closed&sort=updated&direction=desc&per_page=50") or []
    return any(p.get("merged_at") and datetime.strptime(p["merged_at"], "%Y-%m-%dT%H:%M:%SZ")
               .replace(tzinfo=timezone.utc) >= since for p in pulls)


def policy_flags(repo, ref):
    flags = []
    for path in POLICY_FILES:
        text = file_text(repo, path, ref)
        if text:
            hits = sorted({w for w in POLICY_WORDS if w in text.lower()})
            flags.append(path + (f" (mentions: {', '.join(hits)})" if hits else ""))
    return "; ".join(flags)


def history_timeout(repo, file):
    """(timeout minutes, successful job samples) from the workflow's recent runs, or (None, n)."""
    data = maybe(f"repos/{repo}/actions/workflows/{file}/runs?status=completed&per_page={MAX_HISTORY_RUNS}")
    runs = (data or {}).get("workflow_runs", [])
    jobs = {r["id"]: fetch_jobs(repo, r["id"]) for r in runs}
    result = estimate_from_runs(runs, jobs, {file: {"S1"}})
    samples = sum(1 for js in jobs.values() for j in js if j.get("conclusion") == "success")
    return result["timeouts"].get(file), samples


def main():
    if not os.environ.get("GITHUB_TOKEN"):
        raise SystemExit("Set GITHUB_TOKEN to a GitHub personal access token (read-only is enough).")
    with open(os.path.join("rq3", "review_resolved.csv"), newline="", encoding="utf-8") as f:
        reviewed = [r for r in csv.DictReader(f) if r["label"] == "correct"]
    with open(os.path.join("rq3", "snapshot.csv"), newline="", encoding="utf-8") as f:
        snapshot = {r["repo"]: r for r in csv.DictReader(f)}
    random.Random(SEED).shuffle(reviewed)
    os.makedirs(OUT, exist_ok=True)
    rows, used_repos, per_smell = [], set(), {}
    for r in reviewed:
        repo, file, smell = r["repo"], r["file"], r["smell"]
        row = {"id": r["id"], "repo": repo, "file": file, "smell": smell, "status": "skipped", "reason": "",
               "timeout": "", "policy_files": "", "default_branch": ""}
        rows.append(row)
        if repo in used_repos:
            row["reason"] = "repository already has a candidate"
            continue
        if per_smell.get(smell, 0) >= PER_SMELL:
            row["reason"] = "enough candidates for this smell"
            continue
        info = maybe(f"repos/{repo}")
        if not info:
            row["reason"] = "repository not reachable (deleted, renamed or private)"
            continue
        branch = info["default_branch"]
        row["default_branch"] = branch
        if info.get("archived"):
            row["reason"] = "archived"
            continue
        current = file_text(repo, f".github/workflows/{file}", branch)
        with open(os.path.join("rq3", "files", f"{repo.replace('/', '__')}__{file}"), encoding="utf-8",
                  errors="replace") as f:
            snap_text = f.read()
        if current is None:
            row["reason"] = "workflow file no longer exists"
            continue
        if norm(current) != norm(snap_text):
            row["reason"] = "workflow file changed since the snapshot"
            continue
        if smell not in {s for s, _, _ in detect(current)}:
            row["reason"] = "smell no longer detected"
            continue
        if not merged_recently(repo):
            row["reason"] = f"no pull request merged in the last {ACTIVE_DAYS} days"
            continue
        timeout, samples = (None, 0)
        if smell == "S1":
            timeout, samples = history_timeout(repo, file)
            if timeout is None:
                row["reason"] = f"not enough successful job history for a timeout ({samples} jobs)"
                continue
            row["timeout"] = timeout
        fixed, applied = repair(current, repo=repo, default_branch=branch, timeout=timeout, smells={smell})
        if not applied:
            row["reason"] = "current tool makes no repair"
            continue
        checks = check(current, fixed, applied)
        if not all(checks.values()):
            row["reason"] = "safety check failed: " + ", ".join(k for k, v in checks.items() if not v)
            continue
        row["policy_files"] = policy_flags(repo, branch)
        row["status"] = "kept"
        used_repos.add(repo)
        per_smell[smell] = per_smell.get(smell, 0) + 1
        d = os.path.join(OUT, r["id"])
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, file), "w", encoding="utf-8", newline="") as f:
            f.write(fixed)
        with open(os.path.join(d, "diff.patch"), "w", encoding="utf-8") as f:
            f.write(diff(current, fixed, f".github/workflows/{file}"))
        title, why = SMELL_TEXT[smell]
        with open(os.path.join(d, "body.md"), "w", encoding="utf-8") as f:
            f.write(f"Title: ci: {title}\n\n" + BODY.format(file=file, title=title,
                                                           why=why.format(timeout=timeout, samples=samples)))
        print(f"kept {r['id']} {smell} {repo}")
    with open(os.path.join(OUT, "candidates.csv"), "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    tracking = os.path.join(OUT, "tracking.csv")
    if not os.path.exists(tracking):
        with open(tracking, "w", newline="", encoding="utf-8") as f:
            csv.writer(f).writerow(["id", "repo", "smell", "pr_url", "opened_on", "outcome",
                                    "outcome_on", "first_response_on", "maintainer_reason"])
    kept = [r for r in rows if r["status"] == "kept"]
    print(f"\n{len(kept)} pull requests prepared ({', '.join(f'{s}: {n}' for s, n in sorted(per_smell.items()))})")


if __name__ == "__main__":
    main()
